    public function run(): void
    {
        foreach ($this->locations() as $divEn => $division) {
            $divisionModel = Division::firstOrCreate(
                ['name' => $division['bn']],
                ['name_en' => $divEn]
            );

            foreach ($division['districts'] as $distEn => $district) {
                $districtModel = District::firstOrCreate(
                    ['name' => $district['bn'], 'division_id' => $divisionModel->id],
                    ['name_en' => $distEn]
                );

                foreach ($district['upazilas'] as $upazila) {
                    Upazila::firstOrCreate([
                        'district_id' => $districtModel->id,
                        'name' => $upazila,
                    ]);
                }
            }
        }
    }

